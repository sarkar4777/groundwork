"""Writes deploy/k8s/groundwork-edge.yaml: one pod per industrial PC, one container per ECU on its bus.

    python edge/tools/render_k8s.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MACHINES = {
    "EX1": ["engine", "telematics", "safety", "hydraulics", "swing"],
    "TC1": ["engine", "telematics", "safety", "slew", "hoist", "lmi"],
    "HT1": ["engine", "telematics", "safety", "transmission", "payload"],
    "DZ1": ["engine", "telematics", "safety", "transmission", "blade"],
}
MQTT = "mqtt://abenix-mosquitto.abenix.svc.cluster.local:1883"


def container(machine: str, role: str) -> str:
    gw = role == "gateway"
    extra = """
          volumeMounts:
            - {name: plant, mountPath: /plant}"""
    limits = "{cpu: 300m, memory: 160Mi}" if gw else "{cpu: 150m, memory: 96Mi}"
    return f"""        - name: {role}
          image: groundwork-ipc:local
          imagePullPolicy: Never
          env:
            - {{name: GW_MACHINE, value: "{machine}"}}
            - {{name: GW_ROLE, value: "{role}"}}
            - name: GW_SITE
              valueFrom: {{configMapKeyRef: {{name: groundwork-edge, key: site}}}}
            - name: CAN_INTERFACE
              valueFrom: {{configMapKeyRef: {{name: groundwork-edge, key: can_interface}}}}
            - name: CAN_CHANNEL
              valueFrom: {{configMapKeyRef: {{name: groundwork-edge, key: can_channel}}}}
            - name: CAN_HOST
              valueFrom: {{configMapKeyRef: {{name: groundwork-edge, key: can_host}}}}
            - name: MQTT_URL
              valueFrom: {{configMapKeyRef: {{name: groundwork-edge, key: mqtt_url}}}}
          resources:
            requests: {{cpu: 10m, memory: 40Mi}}
            limits: {limits}
          securityContext: {{allowPrivilegeEscalation: false, readOnlyRootFilesystem: true, capabilities: {{drop: [ALL]}}}}{extra}"""


def deployment(machine: str) -> str:
    m = machine.lower()
    roles = MACHINES[machine] + ["controller", "gateway"]
    cs = "\n".join(container(machine, r) for r in roles)
    return f"""---
# {machine}'s industrial PC: {len(roles)} containers share the pod's network, which carries the CAN bus, and one
# in-memory volume, which is the machine itself
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ipc-{m}
  namespace: groundwork-edge
  labels: {{app: groundwork-ipc, machine: "{machine}"}}
spec:
  replicas: 1
  strategy: {{type: Recreate}}
  selector:
    matchLabels: {{app: groundwork-ipc, machine: "{machine}"}}
  template:
    metadata:
      labels: {{app: groundwork-ipc, machine: "{machine}"}}
    spec:
      securityContext: {{runAsNonRoot: true, runAsUser: 10001, fsGroup: 10001}}
      terminationGracePeriodSeconds: 5
      volumes:
        - name: plant
          emptyDir: {{medium: Memory, sizeLimit: 1Mi}}
        - name: candump
          emptyDir: {{sizeLimit: 100Mi}}
      initContainers:
        # the copper: a native sidecar, up before any ECU and running for the life of the pod
        - name: canbus
          image: groundwork-ipc:local
          imagePullPolicy: Never
          restartPolicy: Always
          command: ["python", "-m", "canbus"]
          env:
            - {{name: GW_NODE, value: "ipc-{m}"}}
            - name: CAN_CHANNEL
              valueFrom: {{configMapKeyRef: {{name: groundwork-edge, key: can_channel}}}}
            - {{name: CAN_BITRATE, value: "250000"}}
          startupProbe:
            exec: {{command: ["python", "-c", "import socket; socket.create_connection(('127.0.0.1', 29536), 1)"]}}
            periodSeconds: 1
            failureThreshold: 30
          resources:
            requests: {{cpu: 50m, memory: 48Mi}}
            limits: {{cpu: "1", memory: 160Mi}}
          securityContext: {{allowPrivilegeEscalation: false, readOnlyRootFilesystem: true, capabilities: {{drop: [ALL]}}}}
          volumeMounts:
            - {{name: candump, mountPath: /var/log/candump}}
      containers:
{cs}
"""


def main() -> None:
    head = f"""# Groundwork's four simulated industrial PCs. Generated by edge/tools/render_k8s.py, apply with
#   bash scripts/deploy-k8s.sh edge
# No privileged containers, no NET_ADMIN, no kernel modules. Each pod's CAN bus is its canbus sidecar, a
# bit-timed 250 kbit/s bus emulator serving the socketcand protocol on localhost:29536. Real hardware is config:
# CAN_INTERFACE=socketcan CAN_CHANNEL=can0 on a PC with a PEAK or Kvaser adapter, or CAN_HOST at a real
# socketcand daemon running next to a real bus.
apiVersion: v1
kind: Namespace
metadata:
  name: groundwork-edge
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: groundwork-edge
  namespace: groundwork-edge
data:
  site: northgate
  can_interface: socketcand
  can_channel: vcan0
  can_host: localhost
  mqtt_url: {MQTT}
"""
    out = head + "".join(deployment(m) for m in MACHINES)
    (ROOT / "deploy" / "k8s" / "groundwork-edge.yaml").write_text(out, newline="\n")
    print("wrote deploy/k8s/groundwork-edge.yaml")


if __name__ == "__main__":
    main()
